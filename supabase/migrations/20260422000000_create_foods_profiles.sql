-- ─────────────────────────────────────────────
-- profiles: 회원 한 명당 한 줄
-- ─────────────────────────────────────────────
create table public.profiles (
  -- 회원(auth.users)의 id를 그대로 써요. 계정이 지워지면 이 줄도 지워져요.
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;

create policy "Users can view own profile" on public.profiles
  for select to authenticated
  using (auth.uid() = id);

create policy "Users can insert own profile" on public.profiles
  for insert to authenticated
  with check (auth.uid() = id);

create policy "Users can update own profile" on public.profiles
  for update to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- 회원가입하면(auth.users에 줄이 생기면) profiles에 같은 id로 줄을 만들어요.
-- foods.user_id가 profiles를 가리키기 때문에, 이 줄이 없으면 음식을 저장할 수 없어요.
create or replace function public.handle_new_user()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
as $function$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);

  return new;
end;
$function$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ─────────────────────────────────────────────
-- foods: 음식 기록 한 건이 한 줄
-- ─────────────────────────────────────────────
create table public.foods (
  id bigint generated by default as identity primary key,
  -- 회원 정보(profiles)가 지워지면 그 사람의 기록도 지워져요.
  user_id uuid not null references public.profiles (id) on delete cascade,
  meal_type text not null check (meal_type in ('breakfast', 'lunch', 'dinner')),
  food_name text not null,
  carbs numeric not null check (carbs >= 0),
  protein numeric not null check (protein >= 0),
  fat numeric not null check (fat >= 0),
  created_at timestamptz default now(),
  -- 기본값은 한국 시간 기준 오늘 날짜예요.
  record_date date default ((now() at time zone 'Asia/Seoul'))::date
);

alter table public.foods enable row level security;

create policy "Users can view own foods" on public.foods
  for select to authenticated
  using (auth.uid() = user_id);

create policy "Users can insert own foods" on public.foods
  for insert to authenticated
  with check (auth.uid() = user_id);

create policy "Users can update own foods" on public.foods
  for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can delete own foods" on public.foods
  for delete to authenticated
  using (auth.uid() = user_id);
